  /* Slår bogstaver sammen, så søgningen ikke falder over en bindestreg,
     et mellemrum eller et stort forbogstav. "nr aaby" skal finde
     "Nørre Åby", og "kbh" skal ikke finde noget — vi finder på ikke. */
  function skrab(s) {
    return String(s || '').toLowerCase()
      .replace(/å/g, 'aa').replace(/æ/g, 'ae').replace(/ø/g, 'oe')
      .replace(/[^a-z0-9]/g, '');
  }

  /* Rækkefølgen er hele forskellen mellem en liste, man scanner, og en,
     man bare trykker på:

       1. Byer, der BEGYNDER med det skrevne, står først. Skriver man
          "Odder", er Odder svaret — ikke Odderup.
       2. Derefter de korteste. "Rønne" før "Rønne Havn".
       3. Til sidst alfabetisk, så to søgninger på det samme aldrig
          giver to forskellige lister. */
  function søg(tekst, maks) {
    const q = skrab(tekst);
    if (q.length < 2) return [];
    const træf = [];
    for (const b of BYER) {
      const n = skrab(b[0]);
      const plads = n.indexOf(q);
      /* Postnummeret kan også søges. Fire cifre er den hurtigste vej til
         en by, man kender nummeret på. */
      const nr = String(b[1]).startsWith(q) ? 0 : -1;
      if (plads < 0 && nr < 0) continue;
      træf.push({ navn: b[0], postnr: b[1], lat: b[2], lon: b[3], rang: nr === 0 ? 0 : plads });
    }
    træf.sort((a, b) =>
      a.rang - b.rang ||
      a.navn.length - b.navn.length ||
      a.navn.localeCompare(b.navn, 'da'));
    return træf.slice(0, maks || 6);
  }

  return { søg: søg, antal: BYER.length };
